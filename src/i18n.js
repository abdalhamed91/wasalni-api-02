function toEn(text) {
  if (text == null) return text;
  const s = String(text);
  if (!/[؀-ۿ]/.test(s)) return s;
  if (EXACT[s]) return EXACT[s];
  for (const [re, fn] of TEMPLATES) {
    const m = s.match(re);
    if (m) return fn(m);
  }
  if (/ ← /.test(s)) return route(s);   // «مكان ← مكان» فقط
  return s;   // نص حرّ كتبه مستخدم أو الإدارة — يبقى كما هو
}

const tl = (lang, text) => (lang === 'en' ? toEn(text) : text);
